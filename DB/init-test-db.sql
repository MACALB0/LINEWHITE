-- =========================================================
-- Consulta utilizada durante el login
-- =========================================================

CREATE OR REPLACE FUNCTION FN_CONSULTA_LOGIN(
    REQ_CEDULA VARCHAR(25)
)
RETURNS TABLE(
    ID INTEGER,
    CEDULA VARCHAR(25),
    NOMBRE VARCHAR(100),
    APELLIDOS VARCHAR(100),
    ID_TIPO_USUARIO INTEGER,
    PASSWORD_HASH VARCHAR(255),
    RES_RESPUESTA VARCHAR(2),
    RES_RESPUESTA_MSG VARCHAR(150)
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        U.ID_USUARIO,
        U.CEDULA,
        U.NOMBRES,
        U.APELLIDOS,
        U.ID_TIPO_USUARIO,
        U.PASSWORD_HASH,
        'SI'::VARCHAR(2),
        'USUARIO AUTORIZADO'::VARCHAR(150)
    FROM USUARIOS U
    WHERE U.CEDULA = REQ_CEDULA;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT
            NULL::INTEGER,
            REQ_CEDULA,
            NULL::VARCHAR(100),
            NULL::VARCHAR(100),
            NULL::INTEGER,
            NULL::VARCHAR(255),
            'NO'::VARCHAR(2),
            'USUARIO NO EXISTE'::VARCHAR(150);
    END IF;
END;
$$;

-- =========================================================
-- Consulta utilizada por deserializeUser
