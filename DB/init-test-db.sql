CREATE OR REPLACE FUNCTION FN_CONSULTA_LOGIN_SESION(
    ID_USER INTEGER
)
RETURNS TABLE(
    ID INTEGER,
    CEDULA VARCHAR(25),
    NOMBRE VARCHAR(100),
    APELLIDOS VARCHAR(100),
    ID_TIPO_USUARIO INTEGER,
    RES_RESPUESTA VARCHAR(2),
    RES_RESPUESTA_MSG VARCHAR(150)
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        U.ID_USUARIO,
        U.CEDULA,
        U.NOMBRES,
        U.APELLIDOS,
        U.ID_TIPO_USUARIO,
        'SI'::VARCHAR(2),
        'USUARIO AUTORIZADO'::VARCHAR(150)
    FROM USUARIOS U
    WHERE U.ID_USUARIO = ID_USER;

    IF NOT FOUND THEN
        RETURN QUERY
        SELECT
            NULL::INTEGER,
            NULL::VARCHAR(25),
            NULL::VARCHAR(100),
            NULL::VARCHAR(100),
            NULL::INTEGER,
            'NO'::VARCHAR(2),
            'USUARIO NO EXISTE'::VARCHAR(150);
    END IF;
END;
$$;

